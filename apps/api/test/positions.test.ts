import test from "node:test";
import assert from "node:assert/strict";
import { DISCLOSURE_VERSION, routes, type Opening, type Quote, type Session } from "@impacks/contracts";
import { buildApp } from "../src/app.js";
import { demoProviders, packs } from "../src/providers/demo.js";
import { PackService } from "../src/services/packs.js";

test("owned paper position closes once, preserves its collectible card, and rejects cross-account writes", async t => {
  const providers = demoProviders();
  let marketReads = 0;
  const list = providers.markets.listEligible;
  providers.markets.listEligible = async theme => { marketReads++; return list(theme); };
  const app = buildApp({ providers });
  t.after(() => app.close());
  const session = (await app.inject({ method: "POST", url: routes.login, payload: { displayName: "Collector" } })).json<Session>();
  const headers = { authorization: `Bearer ${session.token}` };
  const quote = (await app.inject({ method: "POST", url: routes.quotes, headers, payload: { packId: "crypto" } })).json<Quote>();
  const opened = (await app.inject({ method: "POST", url: routes.openings, headers: { ...headers, "idempotency-key": "position-open-1" }, payload: { quoteId: quote.id, disclosureVersion: DISCLOSURE_VERSION, paymentProof: `demo:${quote.id}` } })).json<Opening>();
  const card = opened.cards[0];
  const url = `${routes.openings}/${opened.id}/cards/${card.id}/close`;
  const close = (key = "close-position-1") => app.inject({ method: "POST", url, headers: { ...headers, "idempotency-key": key }, payload: { confirmSimulation: true } });
  assert.equal(opened.theme, "crypto");
  assert.equal(card.position?.status, "open");
  assert.equal((await app.inject({ method: "POST", url, payload: { confirmSimulation: true } })).statusCode, 401);
  assert.equal((await app.inject({ method: "POST", url, headers, payload: { confirmSimulation: true } })).statusCode, 400);
  assert.equal((await app.inject({ method: "POST", url, headers: { ...headers, "idempotency-key": "close-position-1" }, payload: {} })).statusCode, 400);
  const results = await Promise.all([close(), close(), close("close-position-2")]);
  assert.ok(results.every(result => result.statusCode === 200));
  assert.deepEqual(results[0].json(), results[1].json());
  assert.equal(marketReads, 2, "one open lookup and one close lookup despite concurrent retries");
  const closed = results[0].json<Opening>();
  assert.equal(closed.cards.length, 3);
  assert.deepEqual(closed.cards[0].order, card.order, "original buy receipt is immutable");
  assert.equal(closed.cards[0].position?.status, "closed");
  assert.equal(closed.cards[0].position?.proceedsCents, card.order.quantity * card.priceCents);
  assert.equal(closed.cards[1].position?.status, "open");
  assert.deepEqual((await app.inject({ url: routes.portfolio, headers })).json().openings, [closed]);
  assert.equal((await close()).statusCode, 200);
  assert.equal(marketReads, 2);
  const reuse = await app.inject({ method: "POST", url: `${routes.openings}/${opened.id}/cards/${opened.cards[1].id}/close`, headers: { ...headers, "idempotency-key": "close-position-2" }, payload: { confirmSimulation: true } });
  assert.equal(reuse.statusCode, 409);
  const other = (await app.inject({ method: "POST", url: routes.login, payload: { displayName: "Other" } })).json<Session>();
  assert.equal((await app.inject({ method: "POST", url, headers: { authorization: `Bearer ${other.token}`, "idempotency-key": "other-close-1" }, payload: { confirmSimulation: true } })).statusCode, 404);
});

test("unconfirmed orders cannot close; unavailable prices leave the position open and retryable", async () => {
  const providers = demoProviders();
  const service = new PackService(packs, providers);
  const quote = service.quote("owner", "crypto");
  const opening = await service.open("owner", quote.id, "open-position-1", `demo:${quote.id}`);
  const card = opening.cards[0];
  const list = providers.markets.listEligible;
  providers.markets.listEligible = async () => [];
  await assert.rejects(service.closePosition("owner", opening.id, card.id, "exit-1"), /unavailable/);
  assert.equal(card.position?.status, "open");
  providers.markets.listEligible = list;
  await service.closePosition("owner", opening.id, card.id, "exit-1");
  assert.equal(card.position?.status, "closed");
  opening.cards[1].order.status = "unknown";
  assert.throws(() => service.closePosition("owner", opening.id, opening.cards[1].id, "exit-2"), /filled/);
  opening.mode = "sandbox";
  assert.throws(() => service.closePosition("owner", opening.id, opening.cards[2].id, "exit-3"), /not connected/);
});
